    fun load(context: Context) {
        if (isLoaded) return
        
        ouiMap.putAll(fallbackOuis)
        
        try {
            // We'll look for a file named 'oui_database.txt' in assets in the future
            // For now, we rely on the expanded fallback list or can add a few hundred more
            isLoaded = true
        } catch (e: Exception) {
            Log.e(TAG, "Failed to load OUI database", e)
        }
    }

    fun getVendor(mac: String?): String? {
        if (mac == null) return null
        val cleanMac = mac.replace(":", "").replace("-", "").uppercase()
        if (cleanMac.length < 6) return null
        
        val prefix = cleanMac.substring(0, 6)
        val formattedPrefix = "${prefix.substring(0,2)}:${prefix.substring(2,4)}:${prefix.substring(4,6)}"
        
        return ouiMap[formattedPrefix]
    }
